package com.xworkz.majigeapp.majige;

public class Majige {
        private String brand;
        private String originVillage;
        private String containerType;
        private double volume;
        private boolean isSalted;
        private double price;
        private String color;

        public void setBrand(String brand) {
            this.brand = brand;
        }

        public String getBrand() {
            return brand;
        }

        public void setOriginVillage(String originVillage) {
            this.originVillage = originVillage;
        }

        public String getOriginVillage() {
            return originVillage;
        }

        public void setContainerType(String containerType) {
            this.containerType = containerType;
        }

        public String getContainerType() {
            return containerType;
        }

        public void setVolume(double volume) {
            this.volume = volume;
        }

        public double getVolume() {
            return volume;
        }

        public void setIsSalted(boolean isSalted) {
            this.isSalted = isSalted;
        }

        public boolean getIsSalted() {
            return isSalted;
        }

        public void setPrice(double price) {
            this.price = price;
        }

        public double getPrice() {
            return price;
        }

        public void setColor(String color) {
            this.color = color;
        }

        public String getColor() {
            return color;
        }
    }


