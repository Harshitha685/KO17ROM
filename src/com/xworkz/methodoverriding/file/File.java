package com.xworkz.methodoverriding.file;

public class File {
        public void open() {
            System.out.println("Opening the file.");
        }

        public void read() {
            System.out.println("Reading the file.");
        }

        public void write() {
            System.out.println("Writing to the file.");
        }

        public void close() {
            System.out.println("Closing the file.");
        }
    }


