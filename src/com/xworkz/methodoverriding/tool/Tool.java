package com.xworkz.methodoverriding.tool;

public class Tool {

        public void use() {
            System.out.println("Using the tool.");
        }

        public void maintain() {
            System.out.println("Maintaining the tool.");
        }

        public void store() {
            System.out.println("Storing the tool.");
        }

        public void inspect() {
            System.out.println("Inspecting the tool for damage.");
        }
    }


