package com.xworkz.methodoverriding.logger;

public class Logger {

        public void logInfo() {
            System.out.println("Logging information message.");
        }

        public void logWarning() {
            System.out.println("Logging warning message.");
        }

        public void logError() {
            System.out.println("Logging error message.");
        }

        public void logDebug() {
            System.out.println("Logging debug message.");
        }
    }


