package com.xworkz.methodoverriding.meal;

public class Meal {

        public void prepare() {
            System.out.println("Preparing the meal.");
        }

        public void serve() {
            System.out.println("Serving the meal.");
        }

        public void eat() {
            System.out.println("Eating the meal.");
        }

        public void cleanUp() {
            System.out.println("Cleaning up after the meal.");
        }
    }


