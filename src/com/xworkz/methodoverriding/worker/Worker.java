package com.xworkz.methodoverriding.worker;

public class Worker {
        public void workType() {
            System.out.println("Performs manual or skilled labor.");
        }

        public void shift() {
            System.out.println("Works in day or night shifts.");
        }

        public void salary() {
            System.out.println("Paid hourly, weekly, or monthly.");
        }

        public void toolsUsed() {
            System.out.println("Uses tools related to their profession.");
        }
    }


