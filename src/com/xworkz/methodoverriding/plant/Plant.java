package com.xworkz.methodoverriding.plant;

public class Plant {
        public void grow() {
            System.out.println("Growing with sunlight and water.");
        }

        public void photosynthesize() {
            System.out.println("Converting sunlight into energy.");
        }

        public void absorbWater() {
            System.out.println("Absorbing water through roots.");
        }

        public void reproduce() {
            System.out.println("Reproducing through seeds.");
        }
    }


