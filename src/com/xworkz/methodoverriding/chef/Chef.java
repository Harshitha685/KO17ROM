package com.xworkz.methodoverriding.chef;

public class Chef {
    public void cook() {
        System.out.println("Cooks a variety of dishes.");
    }

    public void prepareIngredients() {
        System.out.println("Prepares all ingredients before cooking.");
    }

    public void cleanKitchen() {
        System.out.println("Cleans the kitchen after cooking.");
    }

    public void serveFood() {
        System.out.println("Serves food to the customers.");
    }
}



