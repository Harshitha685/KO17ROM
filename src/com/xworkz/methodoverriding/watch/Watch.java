package com.xworkz.methodoverriding.watch;

public class Watch {
        public void showTime() {
            System.out.println("Showing the current time.");
        }

        public void start() {
            System.out.println("Starting the watch.");
        }

        public void stop() {
            System.out.println("Stopping the watch.");
        }

        public void reset() {
            System.out.println("Resetting the watch.");
        }
    }


