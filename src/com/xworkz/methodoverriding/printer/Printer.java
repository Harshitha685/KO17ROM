package com.xworkz.methodoverriding.printer;

public class Printer {

        public void brand() {
            System.out.println("Epson brand.");
        }

        public void printType() {
            System.out.println("Can print in color or black and white.");
        }

        public void speed() {
            System.out.println("Prints 10 pages per minute.");
        }

        public void resolution() {
            System.out.println("600 x 600 dpi.");
        }
    }


