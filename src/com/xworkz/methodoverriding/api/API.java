package com.xworkz.methodoverriding.api;

public class API {
        public void connect() {
            System.out.println("Connecting to the API...");
        }

        public void fetchData() {
            System.out.println("Fetching data from the server...");
        }

        public void sendData() {
            System.out.println("Sending data to the server...");
        }

        public void disconnect() {
            System.out.println("Disconnecting from the API...");
        }
    }


