package com.xworkz.methodoverriding.entertainment;

public class Entertainment {

        public void start() {
            System.out.println("Starting entertainment event.");
        }

        public void perform() {
            System.out.println("Performing general entertainment.");
        }

        public void pause() {
            System.out.println("Pausing entertainment.");
        }

        public void end() {
            System.out.println("Ending entertainment.");
        }
    }


