package com.xworkz.methodoverriding.task;

public class Task {
        public void start() {
            System.out.println("Starting the task.");
        }

        public void perform() {
            System.out.println("Performing the task.");
        }

        public void pause() {
            System.out.println("Pausing the task.");
        }

        public void complete() {
            System.out.println("Completing the task.");
        }
    }


