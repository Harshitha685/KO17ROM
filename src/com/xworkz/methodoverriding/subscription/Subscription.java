package com.xworkz.methodoverriding.subscription;

public class Subscription {
    public void startSubscription() {
        System.out.println("Starting the subscription.");
    }

    public void cancelSubscription() {
        System.out.println("Cancelling the subscription.");
    }

    public void renewSubscription() {
        System.out.println("Renewing the subscription.");
    }

    public void viewDetails() {
        System.out.println("Viewing subscription details.");
    }
}



