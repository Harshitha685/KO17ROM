package com.xworkz.methodoverriding.cleaner;

public class Cleaner {
        public void turnOn() {
            System.out.println("Turning on the cleaner.");
        }

        public void clean() {
            System.out.println("Cleaning in progress.");
        }

        public void turnOff() {
            System.out.println("Turning off the cleaner.");
        }

        public void maintain() {
            System.out.println("Performing regular maintenance.");
        }
    }


