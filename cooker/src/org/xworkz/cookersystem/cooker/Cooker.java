package org.xworkz.cookersystem.cooker;

public class Cooker {


        private String brand;
        private int capacityInLiters;
        private String material;
        private boolean isElectric;
        private String lidType;
        private double price;
        private String color;

        // Setter and Getter for brand
        public void setBrand(String brand) {
            this.brand = brand;
        }

        public String getBrand() {
            return brand;
        }

        // Setter and Getter for capacityInLiters
        public void setCapacityInLiters(int capacityInLiters) {
            this.capacityInLiters = capacityInLiters;
        }

        public int getCapacityInLiters() {
            return capacityInLiters;
        }

        // Setter and Getter for material
        public void setMaterial(String material) {
            this.material = material;
        }

        public String getMaterial() {
            return material;
        }

        // Setter and Getter for isElectric
        public void setIsElectric(boolean isElectric) {
            this.isElectric = isElectric;
        }

        public boolean getIsElectric() {
            return isElectric;
        }

        // Setter and Getter for lidType
        public void setLidType(String lidType) {
            this.lidType = lidType;
        }

        public String getLidType() {
            return lidType;
        }

        // Setter and Getter for price
        public void setPrice(double price) {
            this.price = price;
        }

        public double getPrice() {
            return price;
        }

        // Setter and Getter for color
        public void setColor(String color) {
            this.color = color;
        }

        public String getColor() {
            return color;
        }
    }




