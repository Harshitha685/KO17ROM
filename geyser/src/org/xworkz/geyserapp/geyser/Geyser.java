package org.xworkz.geyserapp.geyser;

public class Geyser {


        private String brand;
        private int capacity;
        private int powerConsumption;
        private boolean isInstant;
        private String color;
        private double heatingTime;
        private double price;

        // Setter and Getter for brand
        public void setBrand(String brand) {
            this.brand = brand;
        }

        public String getBrand() {
            return brand;
        }

        // Setter and Getter for capacity
        public void setCapacity(int capacity) {
            this.capacity = capacity;
        }

        public int getCapacity() {
            return capacity;
        }

        // Setter and Getter for powerConsumption
        public void setPowerConsumption(int powerConsumption) {
            this.powerConsumption = powerConsumption;
        }

        public int getPowerConsumption() {
            return powerConsumption;
        }

        // Setter and Getter for isInstant
        public void setIsInstant(boolean isInstant) {
            this.isInstant = isInstant;
        }

        public boolean getIsInstant() {
            return isInstant;
        }

        // Setter and Getter for color
        public void setColor(String color) {
            this.color = color;
        }

        public String getColor() {
            return color;
        }

        // Setter and Getter for heatingTime
        public void setHeatingTime(double heatingTime) {
            this.heatingTime = heatingTime;
        }

        public double getHeatingTime() {
            return heatingTime;
        }

        // Setter and Getter for price
        public void setPrice(double price) {
            this.price = price;
        }

        public double getPrice() {
            return price;
        }
    }


