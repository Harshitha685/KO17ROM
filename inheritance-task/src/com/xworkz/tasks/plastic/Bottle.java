package com.xworkz.tasks.plastic;

public class Bottle extends Plastic {
    public void bottleType() {
        System.out.println("Bottle Type: Water Bottle");
    }

    public void bottleCapacity() {
        System.out.println("Capacity: 1L");
    }

    public void isReusable() {
        System.out.println("Reusable: Yes");
    }

    public void bottleMaterial() {
        System.out.println("Material: PET Plastic");
    }

    public void bottleShape() {
        System.out.println("Shape: Cylindrical");
    }
}
